#!/usr/bin/env bash
set -euo pipefail
source "$(dirname "$0")/modules.sh"
for module in "${modules[@]}"; do
  cd "$module"
  "$root/scripts/golangci.sh" fmt ./...
  "$root/scripts/golangci.sh" run --enable-only wsl_v5 --fix ./...
  "$root/scripts/golangci.sh" fmt ./...
  "$root/scripts/golangci.sh" run ./...
done
